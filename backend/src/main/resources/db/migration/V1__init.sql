CREATE EXTENSION IF NOT EXISTS postgis;

-- 사용자 · 인증

CREATE TABLE users (
  id                     uuid        PRIMARY KEY,
  email                  text        UNIQUE,
  password_hash          text,
  kakao_id               text        UNIQUE,
  google_sub             text        UNIQUE,
  nickname               text        UNIQUE CHECK (char_length(nickname) BETWEEN 2 AND 12),
  intro                  text        NOT NULL DEFAULT '',
  photo_media_id         uuid,
  share_location_default boolean     NOT NULL DEFAULT true,
  notify_activity_start  boolean     NOT NULL DEFAULT true,
  status                 text        NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DELETED')),
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL,
  deleted_at             timestamptz
);

CREATE TABLE media (
  id         uuid        PRIMARY KEY,
  owner_id   uuid        NOT NULL REFERENCES users (id),
  object_key text        NOT NULL,
  thumb_key  text        NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX media_owner_created_idx ON media (owner_id, created_at);

ALTER TABLE users
  ADD CONSTRAINT users_photo_media_fk FOREIGN KEY (photo_media_id) REFERENCES media (id) ON DELETE SET NULL;

CREATE TABLE refresh_tokens (
  id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    uuid        NOT NULL REFERENCES users (id),
  token_hash text        NOT NULL UNIQUE,
  family_id  uuid        NOT NULL,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX refresh_tokens_user_idx ON refresh_tokens (user_id);
CREATE INDEX refresh_tokens_family_idx ON refresh_tokens (family_id);
CREATE INDEX refresh_tokens_expires_idx ON refresh_tokens (expires_at);

CREATE TABLE password_reset_tokens (
  id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    uuid        NOT NULL REFERENCES users (id),
  token_hash text        NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  used_at    timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX password_reset_tokens_user_idx ON password_reset_tokens (user_id);

CREATE TABLE devices (
  push_token text        PRIMARY KEY,
  user_id    uuid        NOT NULL REFERENCES users (id),
  platform   text        NOT NULL CHECK (platform IN ('ANDROID')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL
);
CREATE INDEX devices_user_idx ON devices (user_id);

CREATE TABLE user_agreements (
  user_id   uuid        NOT NULL REFERENCES users (id),
  type      text        NOT NULL CHECK (type IN ('TERMS', 'PRIVACY', 'MARKETING')),
  version   text        NOT NULL,
  agreed    boolean     NOT NULL,
  agreed_at timestamptz NOT NULL,
  PRIMARY KEY (user_id, type, version)
);

-- 크루

CREATE TABLE crews (
  id             uuid        PRIMARY KEY,
  name           text        NOT NULL UNIQUE,
  intro          text        NOT NULL DEFAULT '',
  photo_media_id uuid        REFERENCES media (id) ON DELETE SET NULL,
  leader_id      uuid        NOT NULL REFERENCES users (id),
  invite_code    text        NOT NULL UNIQUE,
  goal_count     int         NOT NULL DEFAULT 200 CHECK (goal_count > 0),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL,
  deleted_at     timestamptz
);

CREATE TABLE crew_members (
  crew_id   uuid        NOT NULL REFERENCES crews (id),
  user_id   uuid        NOT NULL UNIQUE REFERENCES users (id),
  joined_at timestamptz NOT NULL,
  PRIMARY KEY (crew_id, user_id)
);

CREATE TABLE crew_join_requests (
  id         uuid        PRIMARY KEY,
  crew_id    uuid        NOT NULL REFERENCES crews (id),
  user_id    uuid        NOT NULL REFERENCES users (id),
  status     text        NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELED')),
  decided_by uuid        REFERENCES users (id),
  created_at timestamptz NOT NULL DEFAULT now(),
  decided_at timestamptz
);
CREATE UNIQUE INDEX crew_join_requests_one_pending_idx ON crew_join_requests (user_id) WHERE status = 'PENDING';
CREATE INDEX crew_join_requests_crew_status_idx ON crew_join_requests (crew_id, status);

-- 사람 사이

CREATE TABLE follows (
  follower_id uuid        NOT NULL REFERENCES users (id),
  followee_id uuid        NOT NULL REFERENCES users (id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (follower_id, followee_id),
  CHECK (follower_id <> followee_id)
);
CREATE INDEX follows_followee_idx ON follows (followee_id);

CREATE TABLE blocks (
  blocker_id uuid        NOT NULL REFERENCES users (id),
  blocked_id uuid        NOT NULL REFERENCES users (id),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (blocker_id, blocked_id),
  CHECK (blocker_id <> blocked_id)
);

-- 활동

CREATE TABLE activities (
  id              uuid        PRIMARY KEY,
  user_id         uuid        NOT NULL REFERENCES users (id),
  crew_id         uuid        NOT NULL REFERENCES crews (id),
  status          text        NOT NULL CHECK (status IN ('IN_PROGRESS', 'ENDED')),
  started_at      timestamptz NOT NULL,
  ended_at        timestamptz,
  duration_sec    int         NOT NULL DEFAULT 0 CHECK (duration_sec >= 0),
  paused_sec      int         NOT NULL DEFAULT 0 CHECK (paused_sec >= 0),
  paused          boolean     NOT NULL DEFAULT false,
  paused_at       timestamptz,
  distance_m      int         NOT NULL DEFAULT 0 CHECK (distance_m >= 0),
  steps           int         CHECK (steps >= 0),
  route           geometry(LineString, 4326),
  location_shared boolean     NOT NULL,
  item_count      int         NOT NULL DEFAULT 0 CHECK (item_count >= 0),
  by_category     jsonb       NOT NULL DEFAULT '{}',
  created_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz,
  CHECK (status = 'IN_PROGRESS' OR ended_at IS NOT NULL),
  CHECK (status = 'IN_PROGRESS' OR (paused = false AND paused_at IS NULL)),
  CHECK (paused = (paused_at IS NOT NULL))
);
CREATE UNIQUE INDEX activities_one_in_progress_idx ON activities (user_id) WHERE status = 'IN_PROGRESS';
CREATE INDEX activities_crew_started_idx ON activities (crew_id, started_at);
CREATE INDEX activities_user_started_idx ON activities (user_id, started_at);

CREATE TABLE activity_photos (
  id               uuid        PRIMARY KEY,
  activity_id      uuid        NOT NULL REFERENCES activities (id) ON DELETE CASCADE,
  media_id         uuid        NOT NULL UNIQUE REFERENCES media (id),
  point            geometry(Point, 4326),
  taken_at         timestamptz NOT NULL,
  inference_status text        NOT NULL CHECK (inference_status IN ('OK', 'UNAVAILABLE')),
  model_version    text,
  inference_ms     int,
  order_index      int         NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX activity_photos_activity_idx ON activity_photos (activity_id, order_index);

CREATE TABLE activity_items (
  id                    uuid    PRIMARY KEY,
  activity_id           uuid    NOT NULL REFERENCES activities (id) ON DELETE CASCADE,
  photo_id              uuid    REFERENCES activity_photos (id) ON DELETE CASCADE,
  bbox_x                real,
  bbox_y                real,
  bbox_w                real,
  bbox_h                real,
  ai_predicted_category text    CHECK (ai_predicted_category IN ('CIGARETTE', 'CAN', 'PLASTIC', 'PAPER', 'GLASS', 'VINYL', 'GENERAL')),
  ai_confidence         real,
  final_category        text    NOT NULL CHECK (final_category IN ('CIGARETTE', 'CAN', 'PLASTIC', 'PAPER', 'GLASS', 'VINYL', 'GENERAL')),
  quantity              int     NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 999),
  unclassified          boolean NOT NULL,
  source                text    NOT NULL CHECK (source IN ('AI', 'MANUAL')),
  CHECK (
    (bbox_x IS NULL AND bbox_y IS NULL AND bbox_w IS NULL AND bbox_h IS NULL)
    OR (bbox_x IS NOT NULL AND bbox_y IS NOT NULL AND bbox_w IS NOT NULL AND bbox_h IS NOT NULL AND photo_id IS NOT NULL)
  )
);
CREATE INDEX activity_items_activity_idx ON activity_items (activity_id);

CREATE TABLE live_locations (
  user_id     uuid        PRIMARY KEY REFERENCES users (id),
  activity_id uuid        NOT NULL REFERENCES activities (id) ON DELETE CASCADE,
  crew_id     uuid        NOT NULL,
  point       geometry(Point, 4326),
  paused      boolean     NOT NULL DEFAULT false,
  distance_m  int         NOT NULL DEFAULT 0,
  item_count  int         NOT NULL DEFAULT 0,
  elapsed_sec int         NOT NULL DEFAULT 0,
  updated_at  timestamptz NOT NULL
);
CREATE INDEX live_locations_crew_idx ON live_locations (crew_id);

CREATE TABLE crew_daily_stats (
  crew_id        uuid  NOT NULL REFERENCES crews (id),
  date           date  NOT NULL,
  item_count     int   NOT NULL DEFAULT 0,
  distance_m     int   NOT NULL DEFAULT 0,
  duration_sec   int   NOT NULL DEFAULT 0,
  activity_count int   NOT NULL DEFAULT 0,
  by_category    jsonb NOT NULL DEFAULT '{}',
  PRIMARY KEY (crew_id, date)
);

-- 피드

CREATE TABLE posts (
  id         uuid        PRIMARY KEY,
  crew_id    uuid        NOT NULL REFERENCES crews (id),
  author_id  uuid        NOT NULL REFERENCES users (id),
  text       text        NOT NULL DEFAULT '' CHECK (char_length(text) <= 1000),
  visibility text        NOT NULL CHECK (visibility IN ('CREW', 'PRIVATE')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL,
  deleted_at timestamptz,
  deleted_by uuid        REFERENCES users (id)
);
CREATE INDEX posts_crew_visibility_created_idx ON posts (crew_id, visibility, created_at);
CREATE INDEX posts_author_created_idx ON posts (author_id, created_at);

CREATE TABLE post_media (
  post_id     uuid NOT NULL REFERENCES posts (id),
  media_id    uuid NOT NULL REFERENCES media (id),
  order_index int  NOT NULL CHECK (order_index BETWEEN 0 AND 9),
  PRIMARY KEY (post_id, media_id),
  UNIQUE (post_id, order_index)
);

CREATE TABLE post_likes (
  post_id    uuid        NOT NULL REFERENCES posts (id),
  user_id    uuid        NOT NULL REFERENCES users (id),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (post_id, user_id)
);

CREATE TABLE comments (
  id         uuid        PRIMARY KEY,
  post_id    uuid        NOT NULL REFERENCES posts (id),
  author_id  uuid        NOT NULL REFERENCES users (id),
  text       text        NOT NULL CHECK (char_length(text) BETWEEN 1 AND 500),
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  deleted_by uuid        REFERENCES users (id)
);
CREATE INDEX comments_post_created_idx ON comments (post_id, created_at);

-- 크루 운영

CREATE TABLE notices (
  id         uuid        PRIMARY KEY,
  crew_id    uuid        NOT NULL REFERENCES crews (id),
  author_id  uuid        NOT NULL REFERENCES users (id),
  title      text        NOT NULL CHECK (char_length(title) <= 100),
  body       text        NOT NULL CHECK (char_length(body) <= 3000),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL,
  deleted_at timestamptz
);
CREATE INDEX notices_crew_created_idx ON notices (crew_id, created_at);

CREATE TABLE notice_comments (
  id         uuid        PRIMARY KEY,
  notice_id  uuid        NOT NULL REFERENCES notices (id),
  author_id  uuid        NOT NULL REFERENCES users (id),
  text       text        NOT NULL CHECK (char_length(text) BETWEEN 1 AND 500),
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  deleted_by uuid        REFERENCES users (id)
);
CREATE INDEX notice_comments_notice_created_idx ON notice_comments (notice_id, created_at);

CREATE TABLE chat_messages (
  id         uuid        PRIMARY KEY,
  crew_id    uuid        NOT NULL REFERENCES crews (id),
  seq        bigint      NOT NULL,
  author_id  uuid        NOT NULL REFERENCES users (id),
  text       text        NOT NULL CHECK (char_length(text) BETWEEN 1 AND 500),
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  deleted_by uuid        REFERENCES users (id),
  UNIQUE (crew_id, seq)
);

CREATE TABLE chat_reads (
  crew_id    uuid        NOT NULL REFERENCES crews (id),
  user_id    uuid        NOT NULL REFERENCES users (id),
  last_seq   bigint      NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (crew_id, user_id)
);

CREATE TABLE reports (
  id          uuid        PRIMARY KEY,
  crew_id     uuid        NOT NULL REFERENCES crews (id),
  reporter_id uuid        NOT NULL REFERENCES users (id),
  target_type text        NOT NULL CHECK (target_type IN ('USER', 'POST', 'COMMENT', 'NOTICE_COMMENT', 'CHAT_MESSAGE')),
  target_id   text        NOT NULL,
  reason      text        NOT NULL CHECK (reason IN ('SPAM', 'HATE', 'INAPPROPRIATE_PHOTO', 'PRIVACY', 'OTHER')),
  memo        text        CHECK (char_length(memo) <= 500),
  status      text        NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'RESOLVED')),
  result      text        CHECK (result IN ('DELETE', 'DISMISS')),
  resolved_by uuid        REFERENCES users (id),
  resolved_at timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (reporter_id, target_type, target_id),
  CHECK (reason <> 'OTHER' OR btrim(coalesce(memo, '')) <> '')
);
CREATE INDEX reports_crew_status_idx ON reports (crew_id, status, created_at);

-- 알림

CREATE TABLE notifications (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     uuid        NOT NULL REFERENCES users (id),
  type        text        NOT NULL CHECK (type IN (
                'JOIN_REQUEST', 'JOIN_APPROVED', 'JOIN_REJECTED', 'NOTICE', 'COMMENT', 'CHAT',
                'ACTIVITY_STARTED', 'REPORT', 'REPORT_RESOLVED', 'POST_REMOVED')),
  title       text        NOT NULL,
  detail      text        NOT NULL DEFAULT '',
  unread      boolean     NOT NULL DEFAULT true,
  target_type text        CHECK (target_type IN ('JOIN_REQUESTS', 'REPORTS', 'POST', 'NOTICE', 'CHAT', 'LIVE', 'CREW', 'NOTIFICATIONS')),
  target_id   text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notifications_user_unread_created_idx ON notifications (user_id, unread, created_at);
